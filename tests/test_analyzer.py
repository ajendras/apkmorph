"""Unit tests for APKAnalyzer.

Uses heavy mocking so the suite runs in CI without apktool, Java, Frida,
or real APKs. Covers decompilation, component extraction, keyword search,
string resource parsing, and the Frida simulation fallback.
"""

from pathlib import Path
from unittest.mock import MagicMock, patch

import pytest

from apkmorph.analyzer import APKAnalyzer
from apkmorph.models import AnalysisReport


def test_decompile_mocked():
    analyzer = APKAnalyzer(working_dir=Path("/tmp/test_decomp"))
    fake_apk = "sample.apk"

    with patch("apkmorph.analyzer.run_apktool") as mock_run, patch(
        "apkmorph.analyzer.APK"
    ) as mock_apk_cls, patch.object(
        analyzer, "_extract_string_resources", return_value=(["hello"], {"greeting": "hello"})
    ):
        mock_apk = mock_apk_cls.return_value
        mock_apk.get_package.return_value = "com.example.test"
        mock_apk.get_activities.return_value = ["com.example.test.MainActivity"]
        mock_apk.get_services.return_value = []
        mock_apk.get_receivers.return_value = []
        mock_apk.get_providers.return_value = []
        mock_apk.get_permissions.return_value = ["android.permission.INTERNET"]
        mock_apk.get_main_activity.return_value = "com.example.test.MainActivity"
        mock_apk.get_androidversion_name.return_value = "1.2.3"
        mock_apk.get_androidversion_code.return_value = "123"
        mock_apk.get_min_sdk_version.return_value = 24
        mock_apk.get_target_sdk_version.return_value = 34
        mock_apk.is_signed.return_value = True
        mock_apk.get_certificates.return_value = []

        report = analyzer.decompile(fake_apk)

        assert report.package_name == "com.example.test"
        assert report.version_name == "1.2.3"
        assert "com.example.test.MainActivity" in report.components
        assert report.string_resources == {"greeting": "hello"}
        assert report.metadata["resources_arsc"] == "will be regenerated by Apktool after XML edits"
        mock_run.assert_called_once()
        mock_apk_cls.assert_called_once_with(fake_apk)


def test_extract_components():
    analyzer = APKAnalyzer()
    fake_dir = Path("/fake/decompiled")

    with patch("pathlib.Path.glob") as mock_glob:
        mock_smali_variant = MagicMock()
        mock_smali_variant.is_dir.return_value = True
        mock_file = MagicMock()
        mock_file.relative_to.return_value = Path("com/example/Test.smali")
        mock_smali_variant.rglob.return_value = [mock_file]
        mock_glob.return_value = [mock_smali_variant]

        components = analyzer.extract_components(fake_dir)
        assert "com.example.Test" in components


def test_find_by_keyword_with_dir():
    analyzer = APKAnalyzer()
    fake_dir = Path("/fake")

    with patch.object(analyzer, "extract_components", return_value=["com.test.Foo", "com.test.Bar"]):
        matches = analyzer.find_by_keyword("foo", fake_dir)
        assert any("Foo" in m for m in matches)


def test_observe_runtime_uses_simulation_in_ci():
    analyzer = APKAnalyzer()
    report = AnalysisReport(
        apk_path=Path("test.apk"),
        package_name="com.test.app",
        decompiled_dir=Path("/tmp"),
        components=["com.test.MainActivity"],
        strings=["ad", "analytics", "firebase"],
        string_resources={"ad_text": "Buy now"},
        metadata={},
        size_bytes=4096,
    )

    updated = analyzer.observe_runtime(report, duration=1)

    assert len(updated.runtime_observations) > 2
    obs = " ".join(updated.runtime_observations).lower()
    assert any(k in obs for k in ("ad", "analytics", "oncreate", "onresume"))
    assert updated.metadata.get("runtime_observed") is True
    assert updated.metadata.get("frida_used") is False


def test_string_resource_extraction():
    analyzer = APKAnalyzer()

    mock_tree = MagicMock()
    mock_string = MagicMock()
    mock_string.tag = "string"
    mock_string.text = "Test App"
    mock_string.get.return_value = "app_name"

    mock_item = MagicMock()
    mock_item.tag = "item"
    mock_item.text = "Item text"
    mock_item.get.return_value = None

    mock_tree.iter.return_value = [mock_string, mock_item]

    with patch("xml.etree.ElementTree.parse", return_value=mock_tree), patch(
        "pathlib.Path.exists", return_value=True
    ), patch("pathlib.Path.glob", return_value=[Path("strings.xml")]):
        strings, mapping = analyzer._extract_string_resources(Path("/fake"))
        assert "Test App" in strings
        assert mapping["app_name"] == "Test App"
