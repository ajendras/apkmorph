def test_decompile(tmp_working_dir: Path) -> None:
    with patch("apkmorph.analyzer.run_apktool") as mock_run, patch(
        "apkmorph.analyzer.APK"
    ) as mock_apk_class, patch(
        "apkmorph.analyzer.APKAnalyzer._extract_string_resources"
    ) as mock_extract, patch(
        "apkmorph.analyzer.APKAnalyzer.extract_components"
    ) as mock_extract_comp:
        mock_extract.return_value = (["Test string"], {"app_name": "Example"})
        mock_extract_comp.return_value = ["com.example.app.MainActivity"]

        mock_apk_obj = MagicMock()
        mock_apk_obj.get_activities.return_value = ["com.example.app.MainActivity"]
        mock_apk_obj.get_services.return_value = []
        mock_apk_obj.get_receivers.return_value = []
        mock_apk_obj.get_providers.return_value = []
        mock_apk_obj.get_permissions.return_value = []
        mock_apk_obj.get_package.return_value = "com.example.app"
        mock_apk_obj.get_main_activity.return_value = "com.example.app.MainActivity"
        mock_apk_obj.get_androidversion_name.return_value = "1.0"
        mock_apk_obj.get_androidversion_code.return_value = "1"
        mock_apk_obj.get_min_sdk_version.return_value = 21
        mock_apk_obj.get_target_sdk_version.return_value = 34
        mock_apk_obj.is_signed.return_value = True
        mock_apk_obj.get_certificates.return_value = []
        mock_apk_class.return_value = mock_apk_obj

        analyzer = APKAnalyzer(working_dir=tmp_working_dir)
        report = analyzer.decompile("sample.apk")

        assert report.package_name == "com.example.app"
        assert report.version_name == "1.0"
        assert len(report.components) >= 1
        assert "Test string" in report.strings
        assert mock_run.called
        assert mock_extract.called


def test_extract_components(tmp_path: Path) -> None:
    smali_dir = tmp_path / "smali"
    smali_dir.mkdir()
    (smali_dir / "com").mkdir()
    (smali_dir / "com" / "example").mkdir()
    test_smali = smali_dir / "com" / "example" / "TestClass.smali"
    test_smali.write_text(".class public Lcom/example/TestClass;")

    analyzer = APKAnalyzer()
    components = analyzer.extract_components(tmp_path)

    assert "com.example.TestClass" in components


def test_find_by_keyword(tmp_path: Path) -> None:
    smali_dir = tmp_path / "smali"
    smali_dir.mkdir(parents=True)
    (smali_dir / "com" / "example" / "AdActivity.smali").mkdir(parents=True)
    (smali_dir / "com" / "example" / "AdActivity.smali").write_text("ad related code")

    values_dir = tmp_path / "res" / "values"
    values_dir.mkdir(parents=True)
    strings_xml = values_dir / "strings.xml"
    strings_xml.write_text('<string name="ad_text">Advertisement here</string>')

    analyzer = APKAnalyzer()
    matches = analyzer.find_by_keyword("ad", tmp_path)

    assert any("AdActivity" in m for m in matches)
    assert any("resource:strings.xml" in m for m in matches)
    assert len(matches) <= 30


def test_extract_string_resources(tmp_path: Path) -> None:
    values_dir = tmp_path / "res" / "values"
    values_dir.mkdir(parents=True)
    strings_xml = values_dir / "strings.xml"
    strings_xml.write_text(
        """<?xml version="1.0" encoding="utf-8"?>
<resources>
    <string name="app_name">Test App</string>
    <string name="welcome">Welcome to the app</string>
    <string-array name="options">
        <item>Option 1</item>
        <item>Option 2</item>
    </string-array>
</resources>"""
    )

    analyzer = APKAnalyzer()
    strings, string_map = analyzer._extract_string_resources(tmp_path)

    assert "Test App" in strings
    assert "Welcome to the app" in strings
    assert "Option 1" in strings
    assert string_map["app_name"] == "Test App"
    assert string_map["options"] is None or "options" not in string_map  # array name handling


def test_observe_runtime(sample_report: AnalysisReport) -> None:
    analyzer = APKAnalyzer()
    updated = analyzer.observe_runtime(sample_report, duration=1)

    assert isinstance(updated, AnalysisReport)
    assert len(updated.runtime_observations) > 0
    assert updated.metadata["runtime_observed"] is True
    assert "frida_used" in updated.metadata


def test_simulate_observations() -> None:
    analyzer = APKAnalyzer()
    strings = ["ad banner", "firebase analytics", "crash report"]
    observations, frida_used = analyzer._run_frida_observation(
        "com.example.app", duration=1, strings=strings
    )

    assert not frida_used
    assert any("ad" in obs.lower() for obs in observations)
    assert any("analytics" in obs.lower() for obs in observations)
    assert any("crash_reporting" in obs.lower() for obs in observations)
    assert any("total hooks" in obs for obs in observations)


def test_certificate_fingerprint_extraction() -> None:
    analyzer = APKAnalyzer()
    mock_apk = MagicMock()
    mock_cert = MagicMock()
    mock_cert.get_certificate.return_value = b"fake-cert-bytes"
    mock_apk.get_certificates.return_value = [mock_cert]

    # Simulate the metadata path used in decompile
    fingerprints = [
        hashlib.sha256(
            cert.get_certificate() if hasattr(cert, "get_certificate") else b""
        ).hexdigest()
        for cert in mock_apk.get_certificates()
    ]

    assert len(fingerprints) == 1
    assert len(fingerprints[0]) == 64  # SHA-256 hex length
