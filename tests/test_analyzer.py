"""Tests for the APKAnalyzer.

Covers initialization, decompilation flow, component extraction,
keyword search and string resource parsing. All external tools,
file I/O and Androguard calls are mocked so the test suite runs
cleanly in CI (no apktool, no sample APKs, no Ollama).
"""

import pytest
from pathlib import Path
from unittest.mock import patch, MagicMock

from apkmorph.analyzer import APKAnalyzer
from apkmorph.models import AnalysisReport


class TestAPKAnalyzer:
    """Test suite for APKAnalyzer."""

    def test_init(self):
        """Test analyzer initializes and creates working directory."""
        with patch("pathlib.Path.mkdir") as mock_mkdir:
            analyzer = APKAnalyzer(working_dir="test_dir")
            assert analyzer.working_dir == Path("test_dir")
            mock_mkdir.assert_called_once_with(parents=True, exist_ok=True)

    @patch("apkmorph.analyzer.run_apktool")
    @patch("apkmorph.analyzer.APK")
    @patch("pathlib.Path.stat")
    def test_decompile(self, mock_stat, mock_apk_class, mock_run_apktool):
        """Test full decompilation flow with mocked tools."""
        mock_stat.return_value.st_mtime = 1234567890.0

        # Mock Androguard APK object
        mock_apk = MagicMock()
        mock_apk.get_package.return_value = "com.example.app"
        mock_apk.get_androidversion_name.return_value = "1.2.3"
        mock_apk.get_androidversion_code.return_value = 123
        mock_apk.get_min_sdk_version.return_value = 24
        mock_apk.get_target_sdk_version.return_value = 34
        mock_apk.get_main_activity.return_value = "com.example.app.MainActivity"
        mock_apk.get_activities.return_value = [
            "com.example.app.MainActivity",
            "com.example.app.SettingsActivity",
        ]
        mock_apk.get_services.return_value = ["com.example.app.BackgroundService"]
        mock_apk.get_receivers.return_value = []
        mock_apk.get_providers.return_value = []
        mock_apk.get_permissions.return_value = ["android.permission.INTERNET"]
        mock_apk.is_signed.return_value = True
        mock_apk.get_certificates.return_value = [MagicMock()]
        mock_apk_class.return_value = mock_apk

        # Mock internal helper methods
        with patch.object(
            APKAnalyzer,
            "extract_components",
            return_value=["com.example.app.MainActivity"],
        ) as mock_extract:
            with patch.object(
                APKAnalyzer,
                "_extract_string_resources",
                return_value=(["Sample string"], {"app_name": "Example App"}),
            ) as mock_strings:
                analyzer = APKAnalyzer(working_dir=Path("test_decompiled"))
                report = analyzer.decompile("test_app.apk")

                assert isinstance(report, AnalysisReport)
                assert report.package_name == "com.example.app"
                assert report.version_name == "1.2.3"
                assert report.version_code == 123
                assert report.min_sdk == 24
                assert report.target_sdk == 34
                assert len(report.activities) == 2
                assert "com.example.app.MainActivity" in report.components
                assert report.strings == ["Sample string"]
                assert report.string_resources == {"app_name": "Example App"}
                assert "smali_classes" in report.metadata
                assert report.metadata["resources_arsc"] == "will be regenerated by Apktool after XML edits"

                mock_run_apktool.assert_called_once()
                mock_extract.assert_called_once()
                mock_strings.assert_called_once()

    def test_extract_components(self):
        """Test extraction of components from smali directories (including multidex)."""
        analyzer = APKAnalyzer()
        decomp_dir = Path("fake_decomp")

        with patch("pathlib.Path.glob") as mock_glob:
            mock_smali_dir = MagicMock()
            mock_smali_dir.is_dir.return_value = True
            mock_glob.return_value = [mock_smali_dir]

            with patch.object(analyzer, "_walk_smali") as mock_walk:
                mock_walk.side_effect = lambda d, comps: comps.extend(
                    ["com.example.Class1", "com.example.Class2"]
                )
                components = analyzer.extract_components(decomp_dir)
                assert len(components) == 2
                assert "com.example.Class1" in components
                mock_glob.assert_called_once_with("smali*")

    def test_walk_smali(self):
        """Test internal smali walking logic converts paths to class names."""
        analyzer = APKAnalyzer()
        components: list[str] = []
        root = Path("smali")

        mock_file1 = MagicMock()
        mock_file1.relative_to.return_value = Path("com/example/App.smali")
        mock_file2 = MagicMock()
        mock_file2.relative_to.return_value = Path("com/example/utils/Helper.smali")

        with patch.object(Path, "rglob", return_value=[mock_file1, mock_file2]):
            analyzer._walk_smali(root, components)
            assert "com.example.App" in components
            assert "com.example.utils.Helper" in components

    def test_find_by_keyword(self):
        """Test keyword search across components and XML files."""
        analyzer = APKAnalyzer()
        decomp_path = Path("test_decomp")

        with patch.object(
            analyzer,
            "extract_components",
            return_value=["com.test.AnalyticsTracker", "com.test.UI"],
        ):
            with patch("pathlib.Path.exists", return_value=True):
                with patch("pathlib.Path.rglob") as mock_rglob:
                    mock_xml = MagicMock()
                    mock_xml.name = "strings.xml"
                    mock_rglob.return_value = [mock_xml]
                    with patch.object(
                        Path, "read_text", return_value="<string>analytics tracking</string>"
                    ):
                        matches = analyzer.find_by_keyword("analytics", decomp_path)
                        assert len(matches) > 0
                        assert any("AnalyticsTracker" in m for m in matches)
                        assert any("resource:strings.xml" in m for m in matches)

    def test_find_by_keyword_no_dir(self):
        """Test that find_by_keyword returns empty list when no directory is supplied."""
        analyzer = APKAnalyzer()
        assert analyzer.find_by_keyword("test") == []
        assert analyzer.find_by_keyword("") == []

    def test_extract_string_resources(self):
        """Test parsing of string resources from values/*.xml files."""
        analyzer = APKAnalyzer()
        decomp_path = Path("fake")

        with patch("pathlib.Path.exists", return_value=True):
            with patch("pathlib.Path.glob") as mock_glob:
                mock_file = MagicMock()
                mock_glob.return_value = [mock_file]

                with patch("xml.etree.ElementTree.parse") as mock_et_parse:
                    mock_tree = MagicMock()
                    mock_elem1 = MagicMock()
                    mock_elem1.tag = "string"
                    mock_elem1.text = "TestApp"
                    mock_elem1.get.return_value = "app_name"

                    mock_elem2 = MagicMock()
                    mock_elem2.tag = "string"
                    mock_elem2.text = "Hello World"
                    mock_elem2.get.return_value = "welcome"

                    mock_elem3 = MagicMock()
                    mock_elem3.tag = "item"
                    mock_elem3.text = "Option1"
                    mock_elem3.get.return_value = None

                    mock_tree.iter.return_value = [mock_elem1, mock_elem2, mock_elem3]
                    mock_et_parse.return_value = mock_tree

                    strings, string_map = analyzer._extract_string_resources(decomp_path)

                    assert len(strings) == 3
                    assert "TestApp" in strings
                    assert "Hello World" in strings
                    assert "Option1" in strings
                    assert string_map["app_name"] == "TestApp"
                    assert string_map["welcome"] == "Hello World"

    def test_extract_string_resources_no_values_dir(self):
        """Test graceful handling when res/values directory is absent."""
        analyzer = APKAnalyzer()
        with patch("pathlib.Path.exists", return_value=False):
            strings, string_map = analyzer._extract_string_resources(Path("nowhere"))
            assert strings == []
            assert string_map == {}
