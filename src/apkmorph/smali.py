"""Smali editing utilities.

Provides SmaliEditor for locating methods in decompiled Smali, performing
minimal targeted edits (early returns, NOPs, instruction injection), and
writing changes back safely with backups. All edits are line-based and
preserve original formatting where possible.
"""

from pathlib import Path
from typing import Any, Dict, List, Optional
import re
import shutil


class SmaliEditor:
    """Safe, in-memory editor for Smali files.

    Loads a Smali file, locates methods by signature, supports precise
    injection of instructions (e.g. early returns, NOPs for analytics),
    and writes changes with optional backup. Designed for the minimal
    patches generated by the LLM.
    """

    def __init__(self) -> None:
        """Initialize editor with no file loaded."""
        self._current_path: Optional[Path] = None
        self._lines: List[str] = []
        self._original_lines: List[str] = []
        self._modified = False

    def read_method(
        self, smali_path: str | Path, signature: str
    ) -> Dict[str, Any]:
        """Load Smali file and locate the target method by signature.

        Signature can be a simple method name or a full descriptor
        (e.g. "trackEvent(Ljava/lang/String;)V").

        Args:
            smali_path: Path to .smali file
            signature: Method name or full Smali signature

        Returns:
            Dict containing:
                - start: line index of .method
                - end: line index of .end method
                - body: list of body lines
                - signature: matched signature line
                - location_hint: human readable position

        Raises:
            FileNotFoundError: If smali_path does not exist
            ValueError: If method is not found or file is malformed
        """
        path = Path(smali_path).resolve()
        if not path.exists():
            raise FileNotFoundError(f"Smali file not found: {path}")
        if not str(path).endswith(".smali"):
            raise ValueError("File must be a .smali file")

        self._current_path = path
        content = path.read_text(encoding="utf-8")
        self._lines = content.splitlines(keepends=True)
        self._original_lines = self._lines.copy()
        self._modified = False

        method_info = self._find_method(signature)
        if not method_info:
            available = self._list_methods()
            raise ValueError(
                f"Method '{signature}' not found in {path.name}. "
                f"Available methods: {', '.join(available[:6])}"
            )

        return method_info

    def _find_method(self, signature: str) -> Optional[Dict[str, Any]]:
        """Internal: scan for .method line containing the signature."""
        pattern = re.compile(re.escape(signature), re.IGNORECASE)

        for i, line in enumerate(self._lines):
            stripped = line.strip()
            if stripped.startswith(".method") and pattern.search(stripped):
                # Found start, now find matching .end method
                for j in range(i + 1, len(self._lines)):
                    if self._lines[j].strip().startswith(".end method"):
                        return {
                            "start": i,
                            "end": j,
                            "signature": stripped,
                            "body": self._lines[i + 1 : j],
                            "location_hint": f"lines {i + 1}-{j}",
                            "file": str(self._current_path),
                        }
        return None

    def _list_methods(self) -> List[str]:
        """Return list of all method signatures in the loaded file (for error messages)."""
        methods = []
        for line in self._lines:
            if line.strip().startswith(".method"):
                # Extract everything after .method
                match = re.search(r"\.method\s+(.*)", line.strip())
                if match:
                    methods.append(match.group(1).split()[-1])
        return methods

    def inject_code(
        self,
        location: int,
        new_lines: List[str],
        indent: bool = True,
        comment: Optional[str] = None,
    ) -> None:
        """Insert lines at a specific location (0-based, relative to whole file).

        Args:
            location: Absolute line index in the file where insertion occurs
            new_lines: Lines to insert (without trailing newlines)
            indent: Whether to apply standard 4-space indent
            comment: Optional comment to append explaining the patch

        Raises:
            RuntimeError: If no file is loaded
            IndexError: If location is out of bounds
        """
        if not self._current_path or not self._lines:
            raise RuntimeError("No Smali file loaded. Call read_method() first.")

        if location < 0 or location > len(self._lines):
            raise IndexError(f"Location {location} is out of bounds (0-{len(self._lines)})")

        insert_lines: List[str] = []
        for ln in new_lines:
            line = ln.rstrip()
            if indent and not line.startswith(".") and not line.startswith("    "):
                line = "    " + line
            insert_lines.append(line + "\n")

        if comment:
            insert_lines.append(f"    # {comment} (APK Morph)\n")

        self._lines[location:location] = insert_lines
        self._modified = True

    def nop_at(self, location: int, comment: str = "NOP - disabled by APK Morph") -> None:
        """Replace the instruction at location with nop (common for disabling calls)."""
        if not self._lines:
            raise RuntimeError("No file loaded")

        if 0 <= location < len(self._lines):
            original = self._lines[location].rstrip()
            self._lines[location] = f"    nop  # {comment}\n"
            self._modified = True

    def early_return(
        self,
        location: int,
        return_type: str = "void",
        comment: str = "Early return inserted by APK Morph",
    ) -> None:
        """Insert an early return at the given location.

        Supports void, boolean, int, and object returns with minimal values.
        """
        if not self._lines:
            raise RuntimeError("No file loaded")

        if return_type == "void":
            code = ["return-void"]
        elif return_type in ("boolean", "int", "byte", "short"):
            code = ["const/4 v0, 0x0", "return v0"]
        elif return_type in ("java.lang.String", "object"):
            code = ['const-string v0, ""', "return-object v0"]
        else:
            code = ["return-void"]

        self.inject_code(location, code, indent=True, comment=comment)

    def write_back(self, create_backup: bool = True) -> Path:
        """Write modified lines back to the original file.

        Args:
            create_backup: Whether to create a .bak copy before writing

        Returns:
            Path to the written file

        Raises:
            RuntimeError: If no file loaded or write fails
        """
        if not self._current_path or not self._lines:
            raise RuntimeError("No file loaded to write back")

        if not self._modified:
            return self._current_path

        if create_backup:
            backup_path = self._current_path.with_suffix(".smali.bak")
            shutil.copy2(self._current_path, backup_path)

        try:
            self._current_path.write_text("".join(self._lines), encoding="utf-8")
            self._modified = False
            return self._current_path
        except OSError as exc:
            raise RuntimeError(f"Failed to write Smali file {self._current_path}: {exc}") from exc

    def get_diff(self) -> str:
        """Return a simple unified diff of changes since last read."""
        if not self._original_lines:
            return "No original content to diff against."

        diff_lines = []
        for i, (orig, curr) in enumerate(zip(self._original_lines, self._lines)):
            if orig != curr:
                diff_lines.append(f"- {orig.rstrip()}")
                diff_lines.append(f"+ {curr.rstrip()}")

        # Add any appended lines
        if len(self._lines) > len(self._original_lines):
            for extra in self._lines[len(self._original_lines) :]:
                diff_lines.append(f"+ {extra.rstrip()}")

        return "\n".join(diff_lines) if diff_lines else "No changes detected."

    def reset(self) -> None:
        """Discard in-memory changes and reload from disk."""
        if self._current_path and self._current_path.exists():
            content = self._current_path.read_text(encoding="utf-8")
            self._lines = content.splitlines(keepends=True)
            self._original_lines = self._lines.copy()
            self._modified = False


class SmaliUtils:
    """Static utilities for common Smali patterns."""

    @staticmethod
    def is_invoke_line(line: str) -> bool:
        """Return True if line contains an invoke-* instruction."""
        return bool(re.search(r"^\s+invoke-", line))

    @staticmethod
    def is_return_line(line: str) -> bool:
        """Return True if line contains a return-* instruction."""
        return bool(re.search(r"^\s+return", line))

    @staticmethod
    def extract_class_from_path(smali_path: Path) -> str:
        """Convert smali/com/example/Foo.smali into com.example.Foo."""
        try:
            rel = smali_path.relative_to(smali_path.parents[2])  # skip smali/
            return (
                str(rel)
                .replace("smali/", "")
                .replace("smali_classes2/", "")
                .replace("smali_classes3/", "")
                .replace("/", ".")
                .replace(".smali", "")
            )
        except Exception:
            return smali_path.stem


# Public factory for convenience
def get_editor() -> SmaliEditor:
    """Return a fresh SmaliEditor instance."""
    return SmaliEditor()
